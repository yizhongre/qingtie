import AppKit
import Foundation

public enum ClipboardCodecError: LocalizedError {
    case emptyRecord
    case tooLarge
    case plainTextUnavailable
    case invalidRepresentation
    case writeFailed

    public var errorDescription: String? {
        switch self {
        case .emptyRecord: return "没有可写入的剪贴板内容。"
        case .tooLarge: return "剪贴板内容超过 25 MB，未保存。"
        case .plainTextUnavailable: return "此记录不包含可粘贴的纯文本。"
        case .invalidRepresentation: return "剪贴板记录包含无效格式。"
        case .writeFailed: return "无法写入系统剪贴板。"
        }
    }
}

public enum ClipboardCodec {
    public static let maximumPayloadBytes = 25 * 1_024 * 1_024

    private static let excludedTypes: Set<String> = [
        "org.nspasteboard.transienttype",
        "org.nspasteboard.concealedtype",
        "org.nspasteboard.confidentialtype",
        "org.nspasteboard.autogeneratedtype",
        "de.petermaurer.transientpasteboardtype",
        "com.agilebits.onepassword"
    ]

    public static func capture(
        from pasteboard: NSPasteboard,
        sourceName: String,
        sourceBundleIdentifier: String? = nil
    ) -> ClipboardRecord? {
        let changeCount = pasteboard.changeCount
        guard !hasExcludedType(pasteboard.types ?? []),
              let nativeItems = pasteboard.pasteboardItems, !nativeItems.isEmpty else { return nil }
        var items: [[ClipboardRepresentation]] = []
        var totalBytes = 0
        for nativeItem in nativeItems {
            guard !hasExcludedType(nativeItem.types) else { return nil }
            var representations: [ClipboardRepresentation] = []
            for type in nativeItem.types {
                guard let data = nativeItem.data(forType: type) else { continue }
                guard data.count <= maximumPayloadBytes - totalBytes else { return nil }
                totalBytes += data.count
                representations.append(ClipboardRepresentation(type: type.rawValue, data: data))
            }
            if !representations.isEmpty { items.append(representations) }
        }
        guard !items.isEmpty, pasteboard.changeCount == changeCount else { return nil }
        let now = Date()
        return ClipboardRecord(createdAt: now, lastUsedAt: now, sourceName: sourceName, sourceBundleIdentifier: sourceBundleIdentifier, items: items)
    }

    public static func write(_ record: ClipboardRecord, to pasteboard: NSPasteboard, plainText: Bool = false) throws {
        try validate(record)
        let nativeItems: [NSPasteboardItem]
        if plainText {
            guard let text = record.text else { throw ClipboardCodecError.plainTextUnavailable }
            let item = NSPasteboardItem()
            guard item.setString(text, forType: .string) else { throw ClipboardCodecError.writeFailed }
            nativeItems = [item]
        } else {
            nativeItems = try record.items.map { representations in
                let item = NSPasteboardItem()
                for representation in representations {
                    guard item.setData(representation.data, forType: .init(representation.type)) else {
                        throw ClipboardCodecError.writeFailed
                    }
                }
                return item
            }
        }
        // Construct and validate every item before clearing the user's current clipboard.
        pasteboard.clearContents()
        guard pasteboard.writeObjects(nativeItems) else { throw ClipboardCodecError.writeFailed }
    }

    static func validate(_ record: ClipboardRecord) throws {
        guard !record.items.isEmpty else { throw ClipboardCodecError.emptyRecord }
        var totalBytes = 0
        for item in record.items {
            guard !item.isEmpty else { throw ClipboardCodecError.emptyRecord }
            var types: Set<String> = []
            for representation in item {
                guard !representation.type.isEmpty, types.insert(representation.type).inserted else {
                    throw ClipboardCodecError.invalidRepresentation
                }
                guard representation.data.count <= maximumPayloadBytes - totalBytes else {
                    throw ClipboardCodecError.tooLarge
                }
                totalBytes += representation.data.count
            }
        }
    }

    private static func hasExcludedType(_ types: [NSPasteboard.PasteboardType]) -> Bool {
        types.contains { excludedTypes.contains($0.rawValue.lowercased()) }
    }
}
